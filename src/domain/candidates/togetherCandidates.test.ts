test('R-20: 会社の休日 12/30〜1/3 があるとき。四半期ごとに連休の長い順、同じなら早い順で 5 件まで', () => {
  expect(brief(withFree())).toEqual(SHEET_FREE)
  const [q4, , q2, q3] = find(withFree())
  expect(q4.candidates[0].leaveDays).toEqual(['2026-12-21', '2026-12-22', '2026-12-23', '2026-12-24', '2026-12-25'])
  expect(q2.candidates[0].leaveDays).toEqual(['2027-04-22', '2027-04-23', '2027-04-26', '2027-04-27', '2027-04-28'])
  expect(q3.candidates[0].leaveDays).toEqual(['2027-09-16', '2027-09-17', '2027-09-21', '2027-09-22', '2027-09-24'])
})
test('R-20: 1 日分の日程が入っている日は営業日として数え、飛ばさない。その日をまたぐ D はできない', () => {
  // 日程が無ければ、4/30 を休む D が出る（4〜6 月の先頭は 4/23〜4/30 の 5 日、4/23〜5/5 の 13 連休）
  const q2 = (i: PlannerInput) => brief(i).find(([start]) => start === '2027-04-01')
  expect(q2(withFree({}, noEntries(SHEET)))).toEqual(['2027-04-01', [
    ['2027-04-23', '2027-04-30', '2027-04-23', '2027-05-05', 13],
    ['2027-04-26', '2027-05-06', '2027-04-24', '2027-05-06', 13],
    ['2027-04-27', '2027-05-07', '2027-04-27', '2027-05-09', 13],
    ['2027-04-28', '2027-05-10', '2027-04-28', '2027-05-10', 13],
    ['2027-04-30', '2027-05-11', '2027-04-29', '2027-05-11', 13],
  ]])
  // SHEET には 4/30 の有休の予定がある。4/30 を含む D も、4/30 をまたぐ D も出ない
  expect(q2(withFree())).toEqual(SHEET_FREE[2])
})
