import { findTogetherCandidates } from './togetherCandidates'

const free = (patch: object = {}) => ({ id: 'free', name: 'フリーバカンス', days: 5, usable: null, grantDay: '01-01', together: true, ...patch })
const withFree = (patch: object = {}, base: PlannerInput = SHEET): PlannerInput =>
  ({ ...base, settings: { ...base.settings, leaveTypes: [...base.settings.leaveTypes, free(patch)] } }) as PlannerInput
const noCompany = (i: PlannerInput): PlannerInput => ({ ...i, settings: { ...i.settings, companyHolidays: [] } })
const noEntries = (i: PlannerInput): PlannerInput => ({ ...i, entries: [] })
const find = (i: PlannerInput) =>
  findTogetherCandidates({ cal: restCalendarOf(i), settings: i.settings, entries: i.entries, leaveTypeId: 'free', today: i.today, end: '2027-09-30' }) // R-19 の末日
/** [四半期の初日, [休む最初の日, 休む最後の日, 連休の開始日, 連休の終了日, 連休の日数][]] */
const brief = (i: PlannerInput) =>
  find(i).map((q) => [q.quarterStart, q.candidates.map((c) => [c.leaveDays[0], c.leaveDays.at(-1), c.run.start, c.run.end, c.run.days])])

