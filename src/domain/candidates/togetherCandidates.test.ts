test('R-20・R-19: 末日を過ぎる取り方は出さない（末日を 2026-11-26 に縮めたとき）', () => {
  // 11/16 からの営業日は 11/16〜11/20、11/24〜11/27（11/21・11/22 は土日、11/23 は勤労感謝の日）。
  // 5 日の D の最後の日が 11/26 以前なのは、11/16〜11/20、11/17〜11/24、11/18〜11/25、11/19〜11/26 の 4 つ。
  // 11/20 からの D は 11/20・11/24・11/25・11/26・11/27 で、最後の 11/27 が末日を過ぎるので出ない。
  // 連休: 11/16〜11/20 を休むと 11/14(土)〜11/23(月) の 10 日。ほかは前後が営業日なので、D の最初と最後の日までの 8 日
  const i = withFree()
  const v = findTogetherCandidates({ cal: restCalendarOf(i), settings: i.settings, entries: i.entries, leaveTypeId: 'free', today: i.today, end: '2026-11-26' })
  expect(v.map((q) => [q.quarterStart, q.candidates.map((c) => [c.leaveDays[0], c.leaveDays.at(-1), c.run.start, c.run.end, c.run.days])])).toEqual([
    ['2026-10-01', [
      ['2026-11-16', '2026-11-20', '2026-11-14', '2026-11-23', 10],
      ['2026-11-17', '2026-11-24', '2026-11-17', '2026-11-24', 8],
      ['2026-11-18', '2026-11-25', '2026-11-18', '2026-11-25', 8],
      ['2026-11-19', '2026-11-26', '2026-11-19', '2026-11-26', 8],
    ]],
  ])
})
test('R-20: 使える期間の終わりが末日より前なら、期間の中で始まって外で終わる取り方は出さない', () => {
  // 使える期間 08-23〜08-31。2027 年 8/23(月)〜8/31(火) の営業日は 8/23〜8/27、8/30、8/31 の 7 日（祝日は無い）。
  // 2026 年の 8 月は今日（11/15）より前。5 日の D が期間に収まるのは 8/23〜8/27、8/24〜8/30、8/25〜8/31 の 3 つ。
  // 8/26 からの D（〜9/1）と 8/27 からの D（〜9/2）は、期間の外の 9 月で終わるので出ない。
  // 連休: 8/23〜8/27 を休むと 8/21(土)〜8/29(日) の 9 日。8/24〜8/30 と 8/25〜8/31 は前後が営業日なので 7 日
  expect(brief(withFree({ usable: { start: '08-23', end: '08-31' } }))).toEqual([
    ['2027-07-01', [
      ['2027-08-23', '2027-08-27', '2027-08-21', '2027-08-29', 9],
      ['2027-08-24', '2027-08-30', '2027-08-24', '2027-08-30', 7],
      ['2027-08-25', '2027-08-31', '2027-08-25', '2027-08-31', 7],
    ]],
  ])
})
