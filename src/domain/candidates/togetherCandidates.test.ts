test('R-20: 使える期間があれば、D の全部がその期間に入る', () => {
  expect(brief(withFree({ usable: { start: '07-01', end: '09-30' } }))).toEqual(SHEET_FREE.slice(3))
})
test('R-20: 日数が 1 以上の整数でない種類、印の無い種類、有休の付与日が無いときは出さない', () => {
  expect(find(withFree({ days: 2.5 }))).toEqual([])
  expect(find(withFree({ days: 0 }))).toEqual([])
  expect(find(withFree({ together: false }))).toEqual([])
  expect(find(withFree({}, UNSET))).toEqual([])
})
