import { expect, test } from 'vitest'
import { groupCandidates } from './groupCandidates'

const c = (leaveDays: string[], start: string, end: string, days: number, core: string) => ({ leaveDays, run: { start, end, days }, long: days >= 5, unconfirmed: false, core })

test('F-203・R-5〜R-7: 核でまとめ、四半期の中は効率の大きい組から。組の中は休む日数の少ない順', () => {
  const groups = groupCandidates([
    c(['2026-11-20'], '2026-11-20', '2026-11-23', 4, '2026-11-23'),
    c(['2026-12-28', '2026-12-29'], '2026-12-26', '2027-01-03', 9, '2026-12-30'),
    c(['2026-12-29'], '2026-12-29', '2027-01-03', 6, '2026-12-30'),
    c(['2027-02-12'], '2027-02-11', '2027-02-14', 4, '2027-02-11'),
  ])
  expect(groups.map((g) => [g.quarterStart, g.core])).toEqual([
    ['2026-10-01', '2026-12-30'], // 効率 6（1 日で 6 連休）
    ['2026-10-01', '2026-11-23'], // 効率 4
    ['2027-01-01', '2027-02-11'],
  ])
  expect(groups[0].candidates.map((x) => x.leaveDays.length)).toEqual([1, 2])
})

test('R-6: 組の四半期は最も効率のよい候補の四半期。同点なら休む日数の少ないもの', () => {
  // 1 日で 4 連休（2027-01-04 が先頭）と 2 日で 8 連休（2026-12-31 が先頭）は効率 4 で同点。少ない日数のほうの四半期（翌年 1 月）
  const groups = groupCandidates([
    c(['2026-12-31', '2027-01-04'], '2026-12-29', '2027-01-05', 8, '2027-01-01'),
    c(['2027-01-04'], '2027-01-01', '2027-01-04', 4, '2027-01-01'),
  ])
  expect(groups[0].quarterStart).toBe('2027-01-01')
})

test('R-7: 効率が同じ組は核の早い順', () => {
  const groups = groupCandidates([
    c(['2026-11-20'], '2026-11-20', '2026-11-23', 4, '2026-11-23'),
    c(['2026-11-02'], '2026-10-31', '2026-11-03', 4, '2026-11-03'),
  ])
  expect(groups.map((g) => g.core)).toEqual(['2026-11-03', '2026-11-23'])
})

test('R-7: 組の中は休む日数、並びの長さ（長い順）、最初の日の順', () => {
  const groups = groupCandidates([
    c(['2026-11-10'], '2026-11-07', '2026-11-10', 4, '2026-11-23'),
    c(['2026-11-05'], '2026-11-03', '2026-11-08', 6, '2026-11-23'),
    c(['2026-11-04'], '2026-11-03', '2026-11-08', 6, '2026-11-23'),
  ])
  expect(groups[0].candidates.map((x) => x.leaveDays[0])).toEqual(['2026-11-04', '2026-11-05', '2026-11-10'])
})
